/// A cross-partition message. Every kind knows its target partition without a lookup
/// (see [`OutboxMsg::target_partition`]).
#[derive(Clone, PartialEq, prost::Message)]
pub struct OutboxMsg {
    /// The message kind.
    #[prost(oneof = "outbox_msg::Kind", tags = "1, 2, 3, 4, 5")]
    pub kind: Option<outbox_msg::Kind>,
}

/// Oneof variants of [`OutboxMsg`].
pub mod outbox_msg {
    /// Outbox message kind.
    #[derive(Clone, PartialEq, prost::Oneof)]
    pub enum Kind {
        /// Start a child run (target = the child's partition).
        #[prost(message, tag = "1")]
        StartChild(super::StartChild),
        /// A child completed (target = the parent's partition).
        #[prost(message, tag = "2")]
        ChildCompleted(super::ChildCompleted),
        /// Deliver a signal (target = the target run's partition).
        #[prost(message, tag = "3")]
        Signal(super::Signal),
        /// Cancel a run (target = the target run's partition).
        #[prost(message, tag = "4")]
        CancelRun(super::CancelRun),
        /// Start a run for a cron firing (target = the new run's partition).
        #[prost(message, tag = "5")]
        CronStart(super::CronStart),
    }
}


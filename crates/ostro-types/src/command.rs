//! The partition command set (STOR-01, STOR-10, STOR-12, STOR-13): the `cmds` carried in a log
//! envelope. Hand-written prost messages (no build step).
//!
//! # Format stability
//!
//! - The format is **frozen at the end of Phase 5**. After that, changes are additive only: new
//!   fields, new oneof variants, new enum values.
//! - Field numbers and oneof tags are never reused or renumbered. A removed field's number is
//!   retired forever.
//! - Reserved for future use: `Cmd` tags `8..=63`. Unknown fields are skipped on decode, so an
//!   older binary can read a log that carries newer optional fields.
//! - The bytes are pinned by `tests/golden/commands.txt`.
//!
//! # Ownership split with Phase 3 (design decision, plan 02-06)
//!
//! Apply cannot interpret journal events: their semantics belong to Phase 3 (`journal.rs`). So
//! [`EventsAppended`] carries the events **opaquely** ([`JournalEvent`] = `seq`, `kind: u32`,
//! `payload`) **plus** an explicit list of Phase-2-owned [`Derived`] intents computed by the
//! submitter (the engine host, Phase 4): schedule/cancel a timer, send an outbox message, enqueue
//! the run as ready, complete the run. `Derived` is Phase 2's storage contract.
//!
//! Apply validates fencing (the `(epoch, n)` [`AttemptTokenMsg`]) and applies events and intents
//! atomically. Both travel in the log, so replay stays deterministic. Phase 4 may later move
//! derivation into apply additively (new fields or variants).
//!
//! [`StartRun::rng_seed`] (32 bytes, generated by the submitter) is carried and stored so Phase 3's
//! `RunStarted.rng_seed` has a home; Phase 3 owns its semantics.
//!
//! The helpers in this module are pure and never panic on malformed input: they return errors so
//! apply can produce deterministic `Rejected(Invalid)` outcomes.

use bytes::Bytes;
use prost::Message;

use crate::ids::{AttemptToken, Epoch};
use crate::payload::PayloadRef;

/// One partition command (an element of an envelope's `cmds`).
#[derive(Clone, PartialEq, prost::Message)]
pub struct Command {
    /// The command variant. `None` only for malformed/empty input (apply rejects it as invalid).
    /// Tags 8..=63 are reserved for future variants.
    #[prost(oneof = "Cmd", tags = "1, 2, 3, 4, 5, 6, 7")]
    pub cmd: Option<Cmd>,
}

/// Command variants. Tags are frozen.
#[derive(Clone, PartialEq, prost::Oneof)]
pub enum Cmd {
    /// A new leader epoch begins (fencing, STOR-10).
    #[prost(message, tag = "1")]
    LeaderAnnounced(LeaderAnnounced),
    /// Start a run.
    #[prost(message, tag = "2")]
    StartRun(StartRun),
    /// A run attempt was granted to an executor (fencing token logged, STOR-10).
    #[prost(message, tag = "3")]
    AttemptGranted(AttemptGranted),
    /// Journal events appended by an executor, with derived storage intents.
    #[prost(message, tag = "4")]
    EventsAppended(EventsAppended),
    /// A durable timer fired (STOR-13).
    #[prost(message, tag = "5")]
    TimerFired(TimerFired),
    /// A batch of cross-partition messages from one source partition (STOR-12).
    #[prost(message, tag = "6")]
    InboundBatch(InboundBatch),
    /// The target acknowledged outbox messages up to a sequence number.
    #[prost(message, tag = "7")]
    OutboxTruncated(OutboxTruncated),
}

/// A new leader epoch.
#[derive(Clone, PartialEq, prost::Message)]
pub struct LeaderAnnounced {
    /// The new epoch.
    #[prost(uint32, tag = "1")]
    pub epoch: u32,
    /// Node id of the leader.
    #[prost(uint64, tag = "2")]
    pub node_id: u64,
    /// Wall-clock announcement time (ms since the Unix epoch), set by the submitter.
    #[prost(uint64, tag = "3")]
    pub announced_at_ms: u64,
}

/// Behaviour when a run with the same idempotency key already exists.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, prost::Enumeration)]
#[repr(i32)]
pub enum ConflictPolicy {
    /// Return the existing run.
    ReturnExisting = 0,
    /// Reject the start.
    Reject = 1,
}

/// Terminal status of a run.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, prost::Enumeration)]
#[repr(i32)]
pub enum TerminalStatus {
    /// Completed successfully.
    Completed = 0,
    /// Failed.
    Failed = 1,
    /// Cancelled.
    Cancelled = 2,
}

/// Start a run.
#[derive(Clone, PartialEq, prost::Message)]
pub struct StartRun {
    /// The run id (18 bytes, see [`RunId`]).
    #[prost(bytes = "vec", tag = "1")]
    pub run_id: Vec<u8>,
    /// Workflow name.
    #[prost(string, tag = "2")]
    pub workflow: String,
    /// Workflow version.
    #[prost(uint32, tag = "3")]
    pub workflow_version: u32,
    /// Task queue.
    #[prost(string, tag = "4")]
    pub queue: String,
    /// Run input.
    #[prost(message, optional, tag = "5")]
    pub input: Option<PayloadRef>,
    /// Idempotency key (empty = none).
    #[prost(bytes = "vec", tag = "6")]
    pub idempotency_key: Vec<u8>,
    /// Conflict policy for the idempotency key.
    #[prost(enumeration = "ConflictPolicy", tag = "7")]
    pub conflict_policy: i32,
    /// Concurrency key (empty = none).
    #[prost(string, tag = "8")]
    pub concurrency_key: String,
    /// Scheduling priority.
    #[prost(int32, tag = "9")]
    pub priority: i32,
    /// Earliest time the run may become ready (ms).
    #[prost(uint64, tag = "10")]
    pub ready_at_ms: u64,
    /// Time the start was requested (ms), set by the submitter.
    #[prost(uint64, tag = "11")]
    pub requested_at_ms: u64,
    /// Parent run, for child runs.
    #[prost(message, optional, tag = "12")]
    pub parent: Option<ParentRef>,
    /// 32-byte RNG seed generated by the submitter (semantics: Phase 3 `RunStarted.rng_seed`).
    #[prost(bytes = "vec", tag = "13")]
    pub rng_seed: Vec<u8>,
}

/// A parent run and the operation that started the child.
#[derive(Clone, PartialEq, prost::Message)]
pub struct ParentRef {
    /// Parent run id (18 bytes).
    #[prost(bytes = "vec", tag = "1")]
    pub run_id: Vec<u8>,
    /// Operation id in the parent's journal.
    #[prost(uint64, tag = "2")]
    pub op: u64,
}

/// Wire form of [`AttemptToken`].
#[derive(Clone, Copy, PartialEq, Eq, prost::Message)]
pub struct AttemptTokenMsg {
    /// Epoch that granted the attempt.
    #[prost(uint32, tag = "1")]
    pub epoch: u32,
    /// Attempt counter within the epoch.
    #[prost(uint32, tag = "2")]
    pub n: u32,
}

impl From<AttemptToken> for AttemptTokenMsg {
    fn from(t: AttemptToken) -> Self {
        Self {
            epoch: t.epoch.0,
            n: t.n,
        }
    }
}

impl From<AttemptTokenMsg> for AttemptToken {
    fn from(m: AttemptTokenMsg) -> Self {
        Self {
            epoch: Epoch(m.epoch),
            n: m.n,
        }
    }
}

/// A run attempt was granted.
#[derive(Clone, PartialEq, prost::Message)]
pub struct AttemptGranted {
    /// Run id (18 bytes).
    #[prost(bytes = "vec", tag = "1")]
    pub run_id: Vec<u8>,
    /// The granted fencing token.
    #[prost(message, optional, tag = "2")]
    pub token: Option<AttemptTokenMsg>,
}

/// An opaque journal event. `kind` and `payload` semantics are owned by Phase 3.
#[derive(Clone, PartialEq, prost::Message)]
pub struct JournalEvent {
    /// Journal sequence number.
    #[prost(uint64, tag = "1")]
    pub seq: u64,
    /// Event kind code (Phase 3 `EventKind`).
    #[prost(uint32, tag = "2")]
    pub kind: u32,
    /// Encoded event payload.
    #[prost(message, optional, tag = "3")]
    pub payload: Option<PayloadRef>,
}

/// Journal events appended by the holder of an attempt token, plus derived storage intents.
#[derive(Clone, PartialEq, prost::Message)]
pub struct EventsAppended {
    /// Run id (18 bytes).
    #[prost(bytes = "vec", tag = "1")]
    pub run_id: Vec<u8>,
    /// The executor's fencing token.
    #[prost(message, optional, tag = "2")]
    pub token: Option<AttemptTokenMsg>,
    /// Sequence number of the first event.
    #[prost(uint64, tag = "3")]
    pub from_seq: u64,
    /// The events (opaque to Phase 2).
    #[prost(message, repeated, tag = "4")]
    pub events: Vec<JournalEvent>,
    /// Storage-level consequences, computed by the submitter.
    #[prost(message, repeated, tag = "5")]
    pub derived: Vec<Derived>,
}

/// A Phase-2-owned storage intent derived from journal events.
#[derive(Clone, PartialEq, prost::Message)]
pub struct Derived {
    /// The intent.
    #[prost(oneof = "derived::Intent", tags = "1, 2, 3, 4, 5")]
    pub intent: Option<derived::Intent>,
}

/// Oneof variants of [`Derived`].
pub mod derived {
    /// A storage intent.
    // SendMessage embeds an OutboxMsg (~280 bytes). Boxing it would change the field type the
    // interface pins; intents are short-lived, so the size gap is accepted.
    #[allow(clippy::large_enum_variant)]
    #[derive(Clone, PartialEq, prost::Oneof)]
    pub enum Intent {
        /// Schedule a durable timer.
        #[prost(message, tag = "1")]
        ScheduleTimer(super::ScheduleTimer),
        /// Cancel a durable timer.
        #[prost(message, tag = "2")]
        CancelTimer(super::CancelTimer),
        /// Send a cross-partition (or local) message via the outbox.
        #[prost(message, tag = "3")]
        SendMessage(super::SendMessage),
        /// Mark the run ready to execute.
        #[prost(message, tag = "4")]
        EnqueueReady(super::EnqueueReady),
        /// Complete the run.
        #[prost(message, tag = "5")]
        CompleteRun(super::CompleteRun),
    }
}


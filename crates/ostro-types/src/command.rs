/// Outbox entries for `target` up to and including `upto_seq` were delivered and may be deleted.
#[derive(Clone, PartialEq, prost::Message)]
pub struct OutboxTruncated {
    /// Target partition.
    #[prost(uint32, tag = "1")]
    pub target: u32,
    /// Highest delivered sequence number.
    #[prost(uint64, tag = "2")]
    pub upto_seq: u64,
}

/// Encode a command to its frozen protobuf bytes.
pub fn encode_command(c: &Command) -> Bytes {
    Bytes::from(c.encode_to_vec())
}

/// Decode a command. Malformed input returns an error (never panics); an empty slice decodes to
/// `Command { cmd: None }`.
pub fn decode_command(b: &[u8]) -> Result<Command, prost::DecodeError> {
    Command::decode(b)
}

impl Command {
    fn of(cmd: Cmd) -> Self {
        Self { cmd: Some(cmd) }
    }

    /// `LeaderAnnounced`.
    pub fn leader_announced(epoch: u32, node_id: u64, announced_at_ms: u64) -> Self {
        Self::of(Cmd::LeaderAnnounced(LeaderAnnounced {
            epoch,
            node_id,
            announced_at_ms,
        }))
    }

    /// `StartRun`.
    pub fn start_run(s: StartRun) -> Self {
        Self::of(Cmd::StartRun(s))
    }

    /// `AttemptGranted`.
    pub fn attempt_granted(a: AttemptGranted) -> Self {
        Self::of(Cmd::AttemptGranted(a))
    }

    /// `EventsAppended`.
    pub fn events_appended(e: EventsAppended) -> Self {
        Self::of(Cmd::EventsAppended(e))
    }

    /// `TimerFired`.
    pub fn timer_fired(t: TimerFired) -> Self {
        Self::of(Cmd::TimerFired(t))
    }

    /// `InboundBatch`.
    pub fn inbound_batch(b: InboundBatch) -> Self {
        Self::of(Cmd::InboundBatch(b))
    }

    /// `OutboxTruncated`.
    pub fn outbox_truncated(t: OutboxTruncated) -> Self {
        Self::of(Cmd::OutboxTruncated(t))
    }

    /// Variant name (for logs and metrics); `"None"` for an empty command.
    pub fn kind_name(&self) -> &'static str {
        match &self.cmd {
            None => "None",
            Some(Cmd::LeaderAnnounced(_)) => "LeaderAnnounced",
            Some(Cmd::StartRun(_)) => "StartRun",
            Some(Cmd::AttemptGranted(_)) => "AttemptGranted",
            Some(Cmd::EventsAppended(_)) => "EventsAppended",
            Some(Cmd::TimerFired(_)) => "TimerFired",
            Some(Cmd::InboundBatch(_)) => "InboundBatch",
            Some(Cmd::OutboxTruncated(_)) => "OutboxTruncated",
        }
    }
}

impl OutboxMsg {
    /// A `StartChild` message.
    pub fn start_child(start: StartRun) -> Self {
        Self {
            kind: Some(outbox_msg::Kind::StartChild(StartChild {
                start: Some(start),
            })),
        }
    }
}

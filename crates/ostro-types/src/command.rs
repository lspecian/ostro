//! The partition command set (STOR-01, STOR-10, STOR-12, STOR-13): the `cmds` carried in a log
//! envelope. Hand-written prost messages (no build step).
//!
//! # Format stability
//!
//! - The format is **frozen at the end of Phase 5**. After that, changes are additive only: new
//!   fields, new oneof variants, new enum values.
//! - Field numbers and oneof tags are never reused or renumbered. A removed field's number is
//!   retired forever.
//! - Reserved for future use: `Cmd` tags `14..=19`, `22..=26`, `28..=44` and `46..=63` (blocks
//!   per phase in `.planning/RESERVATIONS.md`; 13 is Phase 6's `CompleteEffect`, 20/21 are
//!   Phase 7's `PauseRun`/`ResumeRun`, 27 is Phase 8's `ScheduleFire`, 45 is Phase 11's
//!   `DlqUpdate`).
//!   Unknown fields are skipped on decode, so an
//!   older binary can read a log that carries newer optional fields.
//! - The bytes are pinned by `tests/golden/commands.txt`.
//!
//! # Ownership split with Phase 3 (design decision, plan 02-06)
//!
//! Apply cannot interpret journal events: their semantics belong to Phase 3 (`journal.rs`). So
//! [`EventsAppended`] carries the events **opaquely** ([`JournalEvent`] = `seq`, `kind: u32`,
//! `payload`) **plus** an explicit list of Phase-2-owned [`Derived`] intents computed by the
//! submitter (the engine host, Phase 4): schedule/cancel a timer, send an outbox message, enqueue
//! the run as ready, complete the run. `Derived` is Phase 2's storage contract.
//!
//! Apply validates fencing (the `(epoch, n)` [`AttemptTokenMsg`]) and applies events and intents
//! atomically. Both travel in the log, so replay stays deterministic. Phase 4 may later move
//! derivation into apply additively (new fields or variants).
//!
//! [`StartRun::rng_seed`] (32 bytes, generated by the submitter) is carried and stored so Phase 3's
//! `RunStarted.rng_seed` has a home; Phase 3 owns its semantics.
//!
//! # Phase 4 additions (plan 04-09, pre-freeze, additive)
//!
//! - [`StartRun`] fields 14..=18: `module_sha`, `tags`, `tenant`, `traceparent`, `run_timeout_ms`.
//!   A StartRun encoded before they existed decodes with empty/zero defaults and re-encodes to
//!   the same bytes. Size limits are the constants below ([`MAX_RUN_TAGS`] etc.); apply enforces
//!   them (plan 04-12, `InvalidCode::FieldTooLong`).
//! - [`derived::Intent::Suspend`] at oneof tag 6: the run waits for an input (timer, signal, ...).
//!   Apply treats `EventsAppended.from_seq` as a compare-and-set on the journal end, so an input
//!   journaled after the executor's last flush makes the Suspend fail (no lost wake-up).
//!
//! # Phase 5 additions (plan 05-01, pre-freeze, additive)
//!
//! Every number below comes from `.planning/RESERVATIONS.md`; decision ids refer to
//! `05-DECISIONS.md`.
//!
//! - [`Cmd`] tags 8..=12: [`SignalRun`], [`RequestCancel`], [`TerminateRun`], [`RetryRun`],
//!   [`CompleteToken`].
//! - [`StartRun`] fields 19..=23: `schedule_to_start_ms` (D2), `retention_ms` (D9), `retry_of`
//!   (D1), `continued_from` (D10), `run_started`.
//! - [`derived::Intent`] tags 7..=8: [`RegisterWait`], [`CancelWait`].
//! - [`CompleteRun`] fields 4 `resumable` (D1) and 5 `parent_event` (D21, Phase 9 PF-F1);
//!   [`ChildCompleted`] field 6 `event`; [`AttemptGranted`] field 3 `after_failure` (F9).
//! - [`TerminalStatus`] 3..=5: `Terminated` (D3), `TimedOut` (D2), `ContinuedAsNew` (D10).
//! - [`outbox_msg::Kind::StartRun`] at tag 6 (continue-as-new, D10).
//! - Reserved timer ops ([`RESERVED_OP_MIN`]..=`u64::MAX`, [`is_reserved_op`]).
//!
//! **D21: submitter-encoded event bytes.** [`SignalRun::event`], [`CompleteToken::event`],
//! [`CompleteRun::parent_event`] and [`ChildCompleted::event`] carry the [`PayloadRef`] (inline,
//! or a blob above 256 KiB) of a **fully encoded journal event**:
//! `[EVENT_CODEC_VER] ‖ postcard((ts_nanos, body))`, ts included, no seq (see
//! `crate::journal`). The submitter builds them; apply stores or forwards them verbatim and never
//! decodes them.
//!
//! # Phase 6 additions (plan 06-02, post-freeze, additive)
//!
//! Every number comes from the P6 block of `.planning/RESERVATIONS.md`; decision ids refer to
//! `06-DECISIONS.md`.
//!
//! - [`Cmd::CompleteEffect`] at tag 13 (FX-01/FX-03, P-10): the bridge's completion of an
//!   http/sql/object effect. Attempt-independent, first completion wins (mirrors
//!   [`CompleteToken`]). **B2:** `outcome` is the PayloadRef of the fully encoded
//!   `EffectCompleted{op, outcome}` (kind 65) event ([`complete_effect_payload`]), stored
//!   verbatim by apply like D21's submitter-encoded events; there is no codec field.
//! - [`derived::Intent`] tags 9..=10: [`RegisterEffect`], [`CancelEffect`] (rows in the existing
//!   `effects` keyspace, #12).
//! - Golden vectors appended (`complete_effect_*`, `events_appended_effects`); every older line
//!   is byte-identical. Apply rejects all three until 06-03.
//!
//! The helpers in this module are pure and never panic on malformed input: they return errors so
//! apply can produce deterministic `Rejected(Invalid)` outcomes.
//!
//! # Phase 8 additions (plan 08-01, post-freeze, additive)
//!
//! - [`Cmd::ScheduleFire`] at tag 27 (RESERVATIONS.md P8 block 27..=33; P8-D10): a cron fire,
//!   a trigger-now (`Manual`) or a watermark-only `Advance` on the schedule's owner partition
//!   ([`crate::routing::schedule_owner`]). Golden vectors appended (`schedule_fire_*`); every
//!   older line is byte-identical. Apply rejects it with `Invalid(NotImplemented)` until 08-07.
//! - Idempotency keys of cron starts: [`cron_idempotency_key`] / [`cron_manual_idempotency_key`].
//!
//! # Phase 7 additions (plan 07-03, post-freeze, additive)
//!
//! - [`Cmd::PauseRun`] at tag 20 and [`Cmd::ResumeRun`] at tag 21 (RESERVATIONS.md P7 block
//!   20..=26; D-W18). Routed by run id like the Phase 5 run commands ([`PauseRun::run_id`],
//!   [`ResumeRun::run_id`]). A `PauseRun` carrying `token` is an executor auto-pause and is
//!   fenced like `EventsAppended`; without it, it is an operator pause. Golden vectors
//!   appended (`pause_run_operator`, `pause_run_auto`, `resume_run`); every older line is
//!   byte-identical. Apply rejects both with `Invalid(NotImplemented)` until 07-04.
//!
//! # Phase 11 additions (plan 11-02, post-freeze, additive)
//!
//! Every number comes from the P11 block of `.planning/RESERVATIONS.md`; decision ids refer to
//! `11-DECISIONS.md`.
//!
//! - [`Cmd::DlqUpdate`] at tag 45 (P11 block 45..=49; OPS-04): a dead-letter membership mark
//!   (`HookStarted`, `Dismissed`, `Requeued`) for one failure episode of a run. Apply rejects
//!   it with `Invalid(NotImplemented)` until 11-08.
//! - [`StartRun`] fields 40 `rerun_prefix` (the journal events `1..cut` copied verbatim) and
//!   41 `rerun_from_seq` (the cut; 0 = not a rerun) (OPS-02). Apply ignores them until 11-07.
//! - [`JournalEvent`] field 4 `attempt` (fixed64, `epoch << 32 | n`; 0 = apply-originated or
//!   unknown). Set by the submitter; apply stores it verbatim and never stamps it.
//! - All three default-omit in proto3, so every older command re-encodes to the same bytes.
//!   Golden vectors appended (`dlq_update_*`, `start_run_rerun`, `events_appended_attempt`).


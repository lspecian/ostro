/// Wire form of [`AttemptToken`].
#[derive(Clone, Copy, PartialEq, Eq, prost::Message)]
pub struct AttemptTokenMsg {
    /// Epoch that granted the attempt.
    #[prost(uint32, tag = "1")]
    pub epoch: u32,
    /// Attempt counter within the epoch.
    #[prost(uint32, tag = "2")]
    pub n: u32,
}

impl From<AttemptToken> for AttemptTokenMsg {
    fn from(t: AttemptToken) -> Self {
        Self {
            epoch: t.epoch.0,
            n: t.n,
        }
    }
}

impl From<AttemptTokenMsg> for AttemptToken {
    fn from(m: AttemptTokenMsg) -> Self {
        Self {
            epoch: Epoch(m.epoch),
            n: m.n,
        }
    }
}


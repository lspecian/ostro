/// Stable journal event kind codes (`JournalEvent.kind`).
///
/// Ranges: 1–15 run record, 16–63 guest commands, 64–127 inputs, 128+ reserved.
/// Codes are frozen with the on-disk format at the end of Phase 5.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[repr(u32)]
pub enum EventKind {
    RunStarted = 1,
    // guest commands
    StepCompleted = 16,
    TimerStarted = 17,
    EffectScheduled = 18,
    SignalWaitStarted = 19,
    ChildStarted = 20,
    AwaitTokenCreated = 21,
    OpCancelled = 22,
    WaitResolved = 23,
    PatchMarker = 24,
    StatusPublished = 25,
    RunCompleted = 26,
    RunFailed = 27,
    RunContinuedAsNew = 28,
    // inputs
    TimerFired = 64,
    EffectCompleted = 65,
    SignalReceived = 66,
    ChildCompleted = 67,
    TokenCompleted = 68,
    CancelRequested = 69,
}

impl EventKind {
    /// Numeric code stored in `JournalEvent.kind`.
    pub fn code(self) -> u32 {
        self as u32
    }
}

